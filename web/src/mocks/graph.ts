import type { EdgeType, GraphEdge, GraphNode } from '../api/types'

const tool = (id: string, name: string, version: string, ecosystem: string, owner_id = 'team_platform'): GraphNode => ({
  id, type: 'tool', name, version, ecosystem, owner_id,
})
const data = (id: string, table: string, column: string, labels: string[], owner_id = 'team_data'): GraphNode => ({
  id, type: 'data', name: `${table}.${column}`, table, column, labels, owner_id,
})
const agent = (id: string, name: string, model_id: string, model_region: string, owner_id = 'team_platform'): GraphNode => ({
  id, type: 'agent', name, model_id, model_region, owner_id,
})
const workflow = (id: string, name: string, owner_id: string, sends_external: boolean): GraphNode => ({
  id, type: 'workflow', name, owner_id, sends_external, state: 'running',
})
const obligation = (id: string, name: string, authority: string, owner_id = 'team_compliance'): GraphNode => ({
  id, type: 'obligation', name, authority, owner_id,
})
const output = (id: string, name: string, channel: string, volume: number | null, owner_id: string): GraphNode => ({
  id, type: 'output', name, channel, volume, owner_id,
})

